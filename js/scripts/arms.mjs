// Generates src/arms.ts from the shipped manifest, so `Arm` and `ArmName` name exactly this build's arms.
import { readFileSync, writeFileSync } from "node:fs";

const { arms } = JSON.parse(readFileSync(new URL("../data/arms.json", import.meta.url)));
const entries = Object.keys(arms).map((name) => `  ${name.toUpperCase()}: ${JSON.stringify(name)},`);
writeFileSync(new URL("../src/arms.ts", import.meta.url), `// Generated by scripts/arms.mjs from data/arms.json — do not edit.
export const Arm = {
${entries.join("\n")}
} as const;

export type ArmName = (typeof Arm)[keyof typeof Arm];
`);
